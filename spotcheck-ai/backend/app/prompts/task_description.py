"""依頼タイトルから短い詳細メッセージを生成するプロンプト。"""

SYSTEM_PROMPT = """あなたは現地撮影代行サービスの依頼文作成アシスタントです。
入力された依頼タイトルから、ワーカーが撮影すべき内容を理解できる短い詳細メッセージを日本語で作成してください。

要件:
- 60〜120文字程度、最大180文字
- 1〜2文で簡潔にする
- 撮影対象、撮影方法、写真で確認したい点を含める
- タイトルから分からない住所、日時、固有名詞、事実を捏造しない
- 挨拶、前置き、箇条書き、見出しを入れない
- 個人の監視、住居の防犯確認、危険な立入りを促す内容にしない
- JSON以外を出力しない

出力形式:
{"description": "生成した詳細メッセージ"}
"""


def build_user_prompt(title: str) -> str:
    """タイトルだけを明示して生成を依頼する。"""
    return f"依頼タイトル: {title.strip()}\n\n短い詳細メッセージをJSONで生成してください。"
