"""プライバシー領域の座標問い合わせプロンプト（docs/04-ai-pipeline.md 5.2）。

ナンバープレートと表札は軽量な物体検出モデルでは精度が出ないため、
**VLM に正規化座標（0〜1）で bbox を返させる。**
"""

from __future__ import annotations

SYSTEM_PROMPT = """あなたは画像内の個人情報領域を検出するAIです。
画像から次の対象の位置を特定し、JSONのみを返してください。
説明文やマークダウンのコードフェンスは一切出力しないでください。

【検出対象 kind】
- face: 人の顔（目・鼻・口が識別できるもの。顔が小さくても検出してください）
- license_plate: 自動車・バイクのナンバープレート（数字や文字が読み取れる板）
- nameplate: 住居の表札（居住者の氏名が書かれたもの）
- address_sign: 番地表示・部屋番号など住所を特定できる表示
- personal_document: 書類・伝票など個人情報が写り込んだ紙面

【座標】画像の左上を (0,0)、右下を (1,1) とする正規化座標で、対象を囲む最小の矩形を
x1（左）, y1（上）, x2（右）, y2（下）として返してください。x1 < x2、y1 < y2 を必ず守ってください。
対象を少し広めに囲んで構いません。

【confidence】その領域が本当に対象であるという確信度を 0.0〜1.0 で返してください。

看板・案内表示・店名など、個人を特定しないものは検出対象に含めないでください。
該当する対象が無ければ regions を空配列にしてください。

【出力フォーマット】次のキーだけを持つJSONオブジェクトを出力してください。
{
  "regions": [
    {"kind": 対象, "x1": 0.0, "y1": 0.0, "x2": 0.0, "y2": 0.0, "confidence": 0.0}
  ]
}"""


def build_user_prompt(*, vehicle_boxes: list[tuple[float, float, float, float]]) -> str:
    """車両の検出結果があれば、プレート探索のヒントとして正規化座標を渡す。"""
    if vehicle_boxes:
        hints = "\n".join(
            f"- 車両{index + 1}: x1={box[0]:.3f}, y1={box[1]:.3f}, x2={box[2]:.3f}, y2={box[3]:.3f}"
            for index, box in enumerate(vehicle_boxes)
        )
        vehicle_part = (
            "この画像では次の位置に車両が検出されています。"
            "ナンバープレートは車両領域の下部にあることが多いので、まずその周辺を確認してください。\n"
            f"{hints}\n"
        )
    else:
        vehicle_part = "この画像では車両は検出されていません。\n"

    return f"{vehicle_part}添付画像から個人情報領域を検出し、JSONのみを出力してください。"
